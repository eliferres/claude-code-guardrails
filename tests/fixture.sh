# Shared fixtures. Sourced by run-tests.sh and by every red case.
# Each test builds its own throwaway project, so no test can see another's state.

make_project() {
  local dir
  dir="$(mktemp -d "${TMPDIR:-/tmp}/guardrails-fixture.XXXXXX")"
  # Resolve through the same realpath the guards use: on macOS $TMPDIR lives under
  # a /var symlink that resolves to /private/var, so an unresolved path here would
  # never match the guard's (already-resolved) target path in test assertions.
  dir="$(python3 -c 'import os,sys;print(os.path.realpath(sys.argv[1]))' "$dir")"
  mkdir -p "$dir/rules" "$dir/notes"
  printf 'team rules\n' > "$dir/rules/team-rules.md"
  printf 'scratch\n' > "$dir/notes/scratch.md"
  cat > "$dir/guardrails.json" <<'JSON'
{
  "command_guard": {
    "rules": [
      {
        "id": "recursive-force-delete",
        "pattern": "\\brm\\s+(-[a-zA-Z]*([rR][a-zA-Z]*[fF]|[fF][a-zA-Z]*[rR])|-[rR]\\s+-[fF]|-[fF]\\s+-[rR]|--recursive\\s+--force|--force\\s+--recursive)",
        "blocks": "a recursive force-delete (rm -rf), which removes a tree with no confirmation and no undo",
        "instead": "delete the named paths (rm path/one path/two), or move them to a trash directory you can inspect"
      },
      {
        "id": "blanket-git-stage",
        "pattern": "\\bgit\\s+(-C\\s+\\S+\\s+)*add\\s+([^|;&]*\\s)?(-A|--all|\\.|\\./)(\\s|$)",
        "blocks": "blanket staging (git add -A / git add .), which sweeps up secrets, local state files and unrelated edits",
        "instead": "stage the files you changed by name: git add src/thing.py tests/test_thing.py"
      },
      {
        "id": "force-push-protected",
        "pattern": "\\bgit\\s+(-C\\s+\\S+\\s+)*push\\b(?=[^|;&]*(--force(?!-with-lease)|\\s-f(\\s|$)))(?=[^|;&]*\\b(main|master)\\b)",
        "blocks": "a force-push to a protected branch, which rewrites history other people have already pulled",
        "instead": "push a branch and open a pull request, or use --force-with-lease on your own branch"
      },
      {
        "id": "curl-pipe-to-shell",
        "pattern": "\\b(curl|wget)\\b[^|;&]*\\|\\s*(sudo\\s+)?(ba|z|k)?sh\\b",
        "blocks": "piping a downloaded script straight into a shell, which executes code nobody read",
        "instead": "download to a file, read it, then run it: curl -fsSL URL -o install.sh && less install.sh && bash install.sh"
      }
    ],
    "allowlist": [
      {
        "rule": "recursive-force-delete",
        "command": "^rm -rf \\./build/cache$",
        "why": "generated build output, regenerated by every build; this exact path only"
      }
    ]
  },
  "file_lock": {
    "protected": ["rules/*.md", "guardrails.json"],
    "token_ttl_seconds": 1800
  },
  "claims": {
    "ttl_seconds": 1800,
    "takeover_ttl_seconds": 600,
    "exempt": [".guardrails/*", "*.log"]
  }
}
JSON
  printf '%s\n' "$dir"
}

bash_payload() {
  printf '{"tool_name":"Bash","tool_input":{"command":"%s"}}' "$1"
}

write_payload() {
  printf '{"tool_name":"Write","tool_input":{"file_path":"%s"},"session_id":"%s"}' "$1" "${2:-cli}"
}
